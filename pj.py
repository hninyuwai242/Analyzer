def levenshtein_distance(s1, s2):
    """စာလုံးနှစ်ခုကြား ကွာခြားမှုကို တွက်တယ်"""
    if len(s1) < len(s2):
        return levenshtein_distance(s2, s1)
    if len(s2) == 0:
        return len(s1)
    
    previous_row = range(len(s2) + 1)
    for i, c1 in enumerate(s1):
        current_row = [i + 1]
        for j, c2 in enumerate(s2):
            insertions = previous_row[j + 1] + 1
            deletions = current_row[j] + 1
            substitutions = previous_row[j] + (c1 != c2)
            current_row.append(min(insertions, deletions, substitutions))
        previous_row = current_row
    
    return previous_row[-1]

def get_suggested_names_smart(name, dataset, max_count=5):
    """Levenshtein distance သုံးပြီး အနီးစပ်ဆုံး နာမည်တွေကိုရှာ"""
    name_clean = re.sub(r'[^a-zA-Z]', '', name).upper()
    if not name_clean:
        return []
    
    scored = []
    for eng_name, mm_name in dataset:
        if not eng_name or eng_name.upper() == name_clean:
            continue
        
        eng_upper = eng_name.upper()
        
        # ၁။ အစစာလုံးတူရင် အမှတ်ပိုရမယ်
        bonus = 0
        if eng_upper[0] == name_clean[0]:
            bonus += 3
        
        # ၂။ အဆုံးစာလုံးတူရင်
        if len(eng_upper) > 0 and len(name_clean) > 0 and eng_upper[-1] == name_clean[-1]:
            bonus += 2
        
        # ၃။ အရေအတွက်ဆင်တူရင်
        if abs(len(eng_upper) - len(name_clean)) <= 2:
            bonus += 1
        
        # Levenshtein distance တွက်
        dist = levenshtein_distance(eng_upper, name_clean)
        
        # အမှတ်နည်းလေ ပိုဆင်တူလေ
        score = dist - bonus
        scored.append((score, eng_name, mm_name))
    
    # အမှတ်နည်းတဲ့အစီအစဉ်
    scored.sort(key=lambda x: x[0])
    
    result = []
    for _, eng, mm in scored[:max_count]:
        result.append(f"{eng} ({mm})")
    
    # မရှိသေးရင် dataset ထဲက ပထမဆုံး နာမည်တွေကိုပြမယ်
    if len(result) == 0:
        for eng, mm in dataset[:max_count]:
            if eng:
                result.append(f"{eng} ({mm})")
    
    return result

