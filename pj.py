# ================= LOAD DATASET =================
def load_dataset():
    data = []
    try:
        with open(DATASET_PATH, 'r', encoding='utf-8') as f:
            try:
                reader = csv.DictReader(f)
                for row in reader:
                    eng = row.get('english', '').strip().upper()
                    mm = row.get('myanmar', '').strip()
                    if eng and mm:
                        data.append((eng, mm))
            except:
                pass

            if len(data) == 0:
                f.seek(0)
                for line in f:
                    if ',' in line:
                        parts = line.strip().split(',')
                        if len(parts) >= 2:
                            eng = parts[0].strip().upper()
                            mm = parts[1].strip()
                            if eng and mm:
                                data.append((eng, mm))
                            
    except FileNotFoundError:
        messagebox.showerror("Error", f"Dataset ဖိုင် မတွေ့ပါ။\n{DATASET_PATH}")
    except Exception as e:
        messagebox.showerror("Error", f"File error:\n{e}")
        
    return data

