def transliterate_mm_to_en(mm_text):
    result = []
    for char in mm_text:
        if char in MM_TO_EN:
            result.append(MM_TO_EN[char])
        elif '\u1000' <= char <= '\u109F':
            continue
        elif char.isspace():
            result.append(' ')
        else:
            result.append(char)
    return ''.join(result).upper()

