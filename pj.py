# ================= DATE VALIDATION =================
def validate_date(date_text):
    date_text = date_text.strip()
    
    mm_year_pattern = r'(\d+)\s*ခုနှစ်'
    mm_month_pattern = r'(တန်ခူး|ကဆုန်|နယုန်|ဝါဆို|ဝါခေါင်|တော်သလင်း|သီတင်းကျွတ်|တန်ဆောင်မုန်း|နတ်တော်|ပြာသို|တပို့တွဲ|တပေါင်း)'
    mm_day_pattern = r'(\d+)\s*ရက်'
    
    match_year = re.search(mm_year_pattern, date_text)
    match_month = re.search(mm_month_pattern, date_text)
    match_day = re.search(mm_day_pattern, date_text)
    
    if match_year and match_month and match_day:
        year = int(match_year.group(1)) + 638
        if year > 2025:
            year = 2025
        day = int(match_day.group(1))
        
        month_map = {
            'တန်ခူး': 4, 'ကဆုန်': 5, 'နယုန်': 6, 'ဝါဆို': 7,
            'ဝါခေါင်': 8, 'တော်သလင်း': 9, 'သီတင်းကျွတ်': 10,
            'တန်ဆောင်မုန်း': 11, 'နတ်တော်': 12, 'ပြာသို': 1,
            'တပို့တွဲ': 2, 'တပေါင်း': 3
        }
        month = month_map.get(match_month.group(1), 1)
        
        try:
            datetime(year, month, day)
            return True, f"{day:02d}.{month:02d}.{year}"
        except ValueError:
            pass
    
    formats = [
        r'^(\d{1,2})[./-](\d{1,2})[./-](\d{4})$',
        r'^(\d{4})[./-](\d{1,2})[./-](\d{1,2})$',
    ]
    
    for pattern in formats:
        match = re.match(pattern, date_text)
        if match:
            groups = match.groups()
            if len(groups) == 3:
                if len(groups[0]) == 4:
                    year, month, day = int(groups[0]), int(groups[1]), int(groups[2])
                else:
                    day, month, year = int(groups[0]), int(groups[1]), int(groups[2])
                
                try:
                    datetime(year, month, day)
                    return True, f"{day:02d}.{month:02d}.{year}"
                except ValueError:
                    return False, None
    
    try:
        from dateutil import parser
        parsed = parser.parse(date_text, fuzzy=True)
        return True, parsed.strftime("%d.%m.%Y")
    except:
        pass
    
    return False, None

